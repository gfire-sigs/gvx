// Command gen writes the C protocol header generated by gpuproto.CHeader.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"z.gfire.dev/gvx/pkg/sentry/devices/virtgpu/gpuproto"
)

func main() {
	outPath := flag.String("o", "", "output file path (required)")
	flag.Parse()

	if *outPath == "" {
		fmt.Fprintln(os.Stderr, "gpuproto gen: -o flag is required")
		os.Exit(1)
	}

	if err := writeFileAtomic(*outPath, gpuproto.CHeader(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gpuproto gen: %v\n", err)
		os.Exit(1)
	}
}

func writeFileAtomic(path string, data []byte, mode os.FileMode) (err error) {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create output directory %s: %w", dir, err)
	}

	tmp, err := os.CreateTemp(dir, ".gvx_gpu_protocol.*.tmp")
	if err != nil {
		return fmt.Errorf("create temporary file in %s: %w", dir, err)
	}
	tmpPath := tmp.Name()
	keep := false
	defer func() {
		if !keep {
			err = errors.Join(err, os.Remove(tmpPath))
		}
	}()

	if _, err := tmp.Write(data); err != nil {
		return errors.Join(fmt.Errorf("write temporary file %s: %w", tmpPath, err), tmp.Close())
	}
	if err := tmp.Chmod(mode); err != nil {
		return errors.Join(fmt.Errorf("chmod temporary file %s: %w", tmpPath, err), tmp.Close())
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temporary file %s: %w", tmpPath, err)
	}
	if err := os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("rename %s to %s: %w", tmpPath, path, err)
	}
	keep = true
	return nil
}
