package ext4lite

import (
	"os"
	"testing"
)

func hostAllocatedBytes(t testing.TB, path string) (allocated, logical int64, supported bool) {
	t.Helper()
	fi, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat %s: %v", path, err)
	}
	return fi.Size(), fi.Size(), false
}
