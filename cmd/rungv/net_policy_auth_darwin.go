package main

import (
	"errors"

	"golang.org/x/sys/unix"
	"z.gfire.dev/gvx/internal/darwinacl"
)

func controlPeerUID(fd int) (uint32, error) {
	cred, err := unix.GetsockoptXucred(fd, unix.SOL_LOCAL, unix.LOCAL_PEERCRED)
	if err != nil {
		return 0, err
	}
	return cred.Uid, nil
}

func validateControlDirectoryACL(path string, private bool) error {
	fd, err := unix.Open(path, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
	if err != nil {
		return err
	}
	return errors.Join(darwinacl.Validate(fd, private), unix.Close(fd))
}

func validateControlInputACL(fd int, private bool) error {
	return darwinacl.Validate(fd, private)
}
