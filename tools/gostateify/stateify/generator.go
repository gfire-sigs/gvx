var (
	errNoPackagesSpecified = errors.New("specify at least one -pkg or -packages-file")
	errDriftDetected       = errors.New("stateify generated file drift detected")
)

// Options configures a gostateify execution across one or more packages.
type Options struct {
	RootDir           string
	Packages          []string
	PackagesFile      string
	PartitionByTier   bool
	Tier2Only         bool
	Check             bool
	SkipMissingTarget bool
}

// DriftRecord describes one file whose on-disk contents differ from generated output.
type DriftRecord struct {
	RelPath string
	Reason  string
	Diff    string
}

// Report summarizes generated, removed, and verified files across inspected packages.
type Report struct {
	PackagesInspected int
	FilesWritten      []string
	FilesRemoved      []string
	FilesVerified     int
	Drifts            []DriftRecord
}

type packageTarget struct {
	absDir    string
	relDir    string
	pkgPath   string
	modPath   string
	tier2Only bool
}

// Run executes gostateify on the configured package list or registered packages file.
func Run(opts Options) (*Report, error) {
	rootDir, modPath, err := resolveRootAndModule(opts.RootDir)
	if err != nil {
		return nil, err
	}
	targets, err := resolvePackageTargets(rootDir, modPath, opts)
	if err != nil {
		return nil, err
	}
	if len(targets) == 0 && !opts.SkipMissingTarget {
		return nil, errNoPackagesSpecified
	}

	report := &Report{}
	for _, target := range targets {
		if err := inspectTarget(rootDir, target, opts, report); err != nil {
			return report, err
		}
		report.PackagesInspected++
	}
	if opts.Check && len(report.Drifts) > 0 {
		var sb strings.Builder
		sb.WriteString(errDriftDetected.Error())
		for _, d := range report.Drifts {
			fmt.Fprintf(&sb, "\n--- %s (%s) ---\n%s", d.RelPath, d.Reason, d.Diff)
		}
		return report, errors.New(sb.String())
	}
	return report, nil
}

// RunPackagesFile regenerates all packages listed in packagesFile under rootDir.
// It returns (nil, nil) when packagesFile does not exist on disk.
func RunPackagesFile(rootDir, packagesFile string) (*Report, error) {
	return RunPackagesFileForSync(rootDir, rootDir, packagesFile)
}

// RunPackagesFileForSync regenerates registered packages inside destRoot during upstream sync.
// Relative packagesFile paths resolve in destRoot first and fall back to rootDir when absent.
func RunPackagesFileForSync(rootDir, destRoot, packagesFile string) (*Report, error) {
	resolvedPath := packagesFile
	if !filepath.IsAbs(resolvedPath) {
		inDest := filepath.Join(destRoot, packagesFile)
		if _, err := os.Stat(inDest); err == nil {
			resolvedPath = inDest
		} else {
			resolvedPath = filepath.Join(rootDir, packagesFile)
		}
	}
	if _, err := os.Stat(resolvedPath); errors.Is(err, os.ErrNotExist) {
		return nil, nil
	} else if err != nil {
		return nil, fmt.Errorf("stat %s: %w", resolvedPath, err)
	}

	absRoot, err := filepath.Abs(rootDir)
	if err != nil {
		return nil, err
	}
	absDest, err := filepath.Abs(destRoot)
	if err != nil {
		return nil, err
	}
	return Run(Options{
		RootDir:           destRoot,
		PackagesFile:      resolvedPath,
		PartitionByTier:   true,
		SkipMissingTarget: absRoot != absDest,
	})
}

func resolveRootAndModule(startDir string) (string, string, error) {
	base := cmp.Or(startDir, ".")
	absBase, err := filepath.Abs(base)
	if err != nil {
		return "", "", fmt.Errorf("resolve root %s: %w", base, err)
	}
	cur := absBase
	for {
		goModPath := filepath.Join(cur, "go.mod")
		if data, err := os.ReadFile(goModPath); err == nil {
			mod := parseModulePath(data)
			return cur, cmp.Or(mod, defaultModulePath), nil
		}
		parent := filepath.Dir(cur)
		if parent == cur {
			return absBase, defaultModulePath, nil
		}
		cur = parent
	}
}

func parseModulePath(goMod []byte) string {
	scanner := bufio.NewScanner(bytes.NewReader(goMod))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if rest, ok := strings.CutPrefix(line, "module "); ok {
			fields := strings.Fields(rest)
			if len(fields) > 0 {
				return strings.Trim(fields[0], `"`)
			}
		}
	}
	return ""
}

func resolvePackageTargets(rootDir, modPath string, opts Options) ([]packageTarget, error) {
	type rawSpec struct {
		pattern   string
		tier2Only bool
	}
	var specs []rawSpec

	if opts.PackagesFile != "" {
		pf := opts.PackagesFile
		if !filepath.IsAbs(pf) {
			pf = filepath.Join(rootDir, pf)
		}
		entries, err := readPackagesFile(pf)
		if err != nil {
			return nil, err
		}
		for _, e := range entries {
			specs = append(specs, rawSpec{
				pattern:   e.pkg,
				tier2Only: opts.Tier2Only || e.tier2Only,
			})
		}
	}

	for _, raw := range opts.Packages {
		for part := range strings.SplitSeq(raw, ",") {
			trimmed := strings.TrimSpace(part)
			if trimmed == "" {
				continue
			}
			specs = append(specs, rawSpec{
				pattern:   trimmed,
				tier2Only: opts.Tier2Only,
			})
		}
	}

	seen := make(map[string]int)
	var out []packageTarget
	for _, spec := range specs {
		expanded, err := expandPattern(rootDir, modPath, spec.pattern, spec.tier2Only, opts.SkipMissingTarget)
		if err != nil {
			return nil, err
		}
		for _, tgt := range expanded {
			if idx, exists := seen[tgt.absDir]; exists {
				out[idx].tier2Only = out[idx].tier2Only && tgt.tier2Only
				continue
			}
			seen[tgt.absDir] = len(out)
			out = append(out, tgt)
		}
	}
	return out, nil
}

type pkgFileEntry struct {
	pkg       string
	tier2Only bool
}

func readPackagesFile(filePath string) ([]pkgFileEntry, error) {
	data, err := os.ReadFile(filePath)
	if err != nil {
		return nil, fmt.Errorf("read packages file %s: %w", filePath, err)
	}
	var entries []pkgFileEntry
	scanner := bufio.NewScanner(bytes.NewReader(data))
	lineNum := 0
	for scanner.Scan() {
		lineNum++
		line := strings.TrimSpace(scanner.Text())
		if idx := strings.IndexByte(line, '#'); idx >= 0 {
			line = strings.TrimSpace(line[:idx])
		}
		if line == "" {
			continue
		}
		fields := strings.Fields(line)
		entry := pkgFileEntry{pkg: fields[0]}
		for _, opt := range fields[1:] {
			switch opt {
			case "tier2":
				entry.tier2Only = true
			default:
				return nil, fmt.Errorf("%s:%d: unsupported option %q", filePath, lineNum, opt)
			}
		}
		entries = append(entries, entry)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("scan %s: %w", filePath, err)
	}
	return entries, nil
}

func expandPattern(rootDir, modPath, pattern string, tier2Only, skipMissing bool) ([]packageTarget, error) {
	if filepath.IsAbs(pattern) && !strings.HasSuffix(pattern, "...") {
		if skipMissing {
			if _, err := os.Stat(pattern); errors.Is(err, os.ErrNotExist) {
				return nil, nil
			}
		}
		return []packageTarget{buildTargetFromAbs(rootDir, modPath, filepath.Clean(pattern), tier2Only)}, nil
	}

	norm := filepath.ToSlash(pattern)
	if modPath != "" && (norm == modPath || strings.HasPrefix(norm, modPath+"/")) {
		norm = strings.TrimPrefix(norm, modPath)
		norm = strings.TrimPrefix(norm, "/")
	}
	norm = strings.TrimPrefix(norm, "./")

	wildcard := false
	switch {
	case norm == "...":
		norm = "."
		wildcard = true
	case strings.HasSuffix(norm, "/..."):
		norm = strings.TrimSuffix(norm, "/...")
		wildcard = true
	}

	var baseAbs string
	if filepath.IsAbs(pattern) {
		baseAbs = filepath.Clean(strings.TrimSuffix(pattern, string(filepath.Separator)+"..."))
	} else {
		baseAbs = filepath.Join(rootDir, filepath.FromSlash(norm))
	}

	info, err := os.Stat(baseAbs)
	if err != nil {
		if skipMissing && errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, fmt.Errorf("stat package path %s: %w", pattern, err)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("package path %s is not a directory", pattern)
	}

	if !wildcard {
		return []packageTarget{buildTargetFromAbs(rootDir, modPath, baseAbs, tier2Only)}, nil
	}

	var targets []packageTarget
	walkErr := filepath.WalkDir(baseAbs, func(dir string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if dir != baseAbs {
			if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") || name == "testdata" || name == "vendor" {
				return filepath.SkipDir
			}
			if _, modErr := os.Stat(filepath.Join(dir, "go.mod")); modErr == nil {
				return filepath.SkipDir
			}
		}
		ok, checkErr := dirNeedsStateify(dir)
		if checkErr != nil {
			return checkErr
		}
		if ok {
			targets = append(targets, buildTargetFromAbs(rootDir, modPath, dir, tier2Only))
		}
		return nil
	})
	if walkErr != nil {
		return nil, walkErr
	}
	return targets, nil
}

func buildTargetFromAbs(rootDir, modPath, absDir string, tier2Only bool) packageTarget {
	localRoot, localMod, err := resolveRootAndModule(absDir)
	useRoot := rootDir
	useMod := modPath
	if err == nil && !isWithinDir(absDir, rootDir) {
		useRoot = localRoot
		useMod = localMod
	}

	rel, relErr := filepath.Rel(useRoot, absDir)
	relSlash := filepath.ToSlash(rel)
	if relErr != nil || strings.HasPrefix(relSlash, "..") {
		base := filepath.Base(absDir)
		return packageTarget{
			absDir:    absDir,
			relDir:    base,
			pkgPath:   base,
			modPath:   useMod,
			tier2Only: tier2Only,
		}
	}
	if relSlash == "." {
		return packageTarget{
			absDir:    absDir,
			relDir:    ".",
			pkgPath:   useMod,
			modPath:   useMod,
			tier2Only: tier2Only,
		}
	}
	pkgPath := relSlash
	if useMod != "" {
		pkgPath = useMod + "/" + relSlash
	}
	return packageTarget{
		absDir:    absDir,
		relDir:    relSlash,
		pkgPath:   pkgPath,
		modPath:   useMod,
		tier2Only: tier2Only,
	}
}

func isWithinDir(target, root string) bool {
	rel, err := filepath.Rel(root, target)
	if err != nil {
		return false
	}
	slash := filepath.ToSlash(rel)
	return slash == "." || (!strings.HasPrefix(slash, "../") && slash != "..")
}

func dirNeedsStateify(dir string) (bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	hasSource := false
	hasMarker := false
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		if strings.HasSuffix(name, "_state_autogen.go") {
			hasMarker = true
			continue
		}
		hasSource = true
		if !hasMarker {
			raw, readErr := os.ReadFile(filepath.Join(dir, name))
			if readErr != nil {
				return false, readErr
			}
			if bytes.Contains(raw, []byte("+stateify")) {
				hasMarker = true
			}
		}
	}
	return hasSource && hasMarker, nil
}

// GeneratedFile holds one formatted autogen file or a removal marker when Present is false.
type GeneratedFile struct {
	Partition PartitionKind
	BaseName  string
	Present   bool
	Content   []byte
}

func inspectTarget(rootDir string, target packageTarget, opts Options, report *Report) error {
	outputs, err := GeneratePackage(target.absDir, target.relDir, target.pkgPath, target.modPath, opts.PartitionByTier, target.tier2Only)
	if err != nil {
		return fmt.Errorf("generate %s: %w", target.relDir, err)
	}

	for _, out := range outputs {
		fullPath := filepath.Join(target.absDir, out.BaseName)
		relFile := out.BaseName
		if rel, relErr := filepath.Rel(rootDir, fullPath); relErr == nil && !strings.HasPrefix(filepath.ToSlash(rel), "..") {
			relFile = filepath.ToSlash(rel)
		}

		diskBytes, readErr := os.ReadFile(fullPath)
		existsOnDisk := readErr == nil
		if readErr != nil && !errors.Is(readErr, os.ErrNotExist) {
			return fmt.Errorf("read %s: %w", fullPath, readErr)
		}
		// Normalize CRLF from Windows core.autocrlf checkouts before comparing against gofmt LF output.
		diskNormalized := bytes.ReplaceAll(diskBytes, []byte("\r\n"), []byte("\n"))

		if !out.Present {
			if !existsOnDisk {
				continue
			}
			if opts.Check {
				report.Drifts = append(report.Drifts, DriftRecord{
					RelPath: relFile,
					Reason:  "stale file exists on disk",
					Diff:    unifiedLineDiff(relFile, string(diskNormalized), ""),
				})
				continue
			}
			if err := os.Remove(fullPath); err != nil {
				return fmt.Errorf("remove stale %s: %w", fullPath, err)
			}
			report.FilesRemoved = append(report.FilesRemoved, relFile)
			continue
		}

		if opts.Check {
			report.FilesVerified++
			if !existsOnDisk {
				report.Drifts = append(report.Drifts, DriftRecord{
					RelPath: relFile,
					Reason:  "missing on disk",
					Diff:    unifiedLineDiff(relFile, "", string(out.Content)),
				})
				continue
			}
			if !bytes.Equal(diskNormalized, out.Content) {
				report.Drifts = append(report.Drifts, DriftRecord{
					RelPath: relFile,
					Reason:  "content mismatch",
					Diff:    unifiedLineDiff(relFile, string(diskNormalized), string(out.Content)),
				})
			}
			continue
		}

		if existsOnDisk && bytes.Equal(diskBytes, out.Content) {
			report.FilesVerified++
			continue
		}
		if err := os.WriteFile(fullPath, out.Content, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", fullPath, err)
		}
		report.FilesWritten = append(report.FilesWritten, relFile)
	}
	return nil
}

