// GeneratePackage parses all non-test, non-autogen Go files in absDir and returns the
// formatted autogen outputs for each partition and build-constraint sub-partition.
func GeneratePackage(absDir, relDir, pkgPath, modPath string, partitionByTier, tier2Only bool) ([]GeneratedFile, error) {
	entries, err := os.ReadDir(absDir)
	if err != nil {
		return nil, fmt.Errorf("read dir %s: %w", absDir, err)
	}

	pkgTier := ClassifyPackage(relDir)
	fset := token.NewFileSet()

	var sourceNames []string
	var rawAutogenNames []string
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		if strings.HasSuffix(name, "_state_autogen.go") {
			rawAutogenNames = append(rawAutogenNames, name)
			continue
		}
		sourceNames = append(sourceNames, name)
	}
	slices.Sort(sourceNames)
	slices.Sort(rawAutogenNames)
	if len(sourceNames) == 0 {
		return nil, fmt.Errorf("no non-autogen Go source files in %s", absDir)
	}

	var pkgName string
	files := make([]*parsedSourceFile, 0, len(sourceNames))

	for _, name := range sourceNames {
		fullPath := filepath.Join(absDir, name)
		src, readErr := os.ReadFile(fullPath)
		if readErr != nil {
			return nil, fmt.Errorf("read %s: %w", fullPath, readErr)
		}
		fileConstraint, cErr := ExtractFileConstraint(name, src)
		if cErr != nil {
			return nil, cErr
		}
		astFile, pErr := parser.ParseFile(fset, fullPath, src, parser.ParseComments)
		if pErr != nil {
			return nil, fmt.Errorf("parse %s: %w", fullPath, pErr)
		}
		if pkgName == "" {
			pkgName = astFile.Name.Name
		}

		pf := &parsedSourceFile{
			baseName:   name,
			partition:  ClassifyFilePartition(pkgTier, name, partitionByTier),
			constraint: fileConstraint,
			astFile:    astFile,
			imports:    collectFileImports(astFile),
		}

		for _, decl := range astFile.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, s := range d.Specs {
					ts, ok := s.(*ast.TypeSpec)
					if !ok || ts.TypeParams != nil {
						continue
					}
					pf.localTypes = append(pf.localTypes, namedLocalType{
						name: ts.Name.Name,
						def: localTypeDef{
							rhs:     ts.Type,
							isAlias: ts.Assign.IsValid(),
						},
					})
				}
			case *ast.FuncDecl:
				if d.Recv == nil || len(d.Recv.List) == 0 {
					continue
				}
				recvField := d.Recv.List[0]
				recvType := baseReceiverTypeName(recvField.Type)
				if recvType == "" {
					continue
				}
				recvVar := ""
				if len(recvField.Names) > 0 && !reservedReceiverNames[recvField.Names[0].Name] {
					recvVar = recvField.Names[0].Name
				}
				pf.methods = append(pf.methods, methodSighting{
					recvType: recvType,
					recvVar:  recvVar,
					funcName: d.Name.Name,
				})
			}
		}
		files = append(files, pf)
	}

	claimedByAuxAutogen, err := findAuxiliaryTier3AutogenTypes(fset, absDir, pkgName, pkgTier, rawAutogenNames)
	if err != nil {
		return nil, err
	}

	partFiles := make(map[PartitionKind][]*parsedSourceFile)
	partTypes := make(map[PartitionKind][]*savableTypeGen)
	for _, pf := range files {
		partFiles[pf.partition] = append(partFiles[pf.partition], pf)
		if tier2Only && !isSiblingPartition(pf.partition) {
			continue
		}
		savables, extractErr := extractSavableTypes(fset, pf, claimedByAuxAutogen)
		if extractErr != nil {
			return nil, extractErr
		}
		partTypes[pf.partition] = append(partTypes[pf.partition], savables...)
	}

	normPkg := normalizeTypePkgPath(pkgPath, modPath)
	stateImportPath := resolveStateImportPath(modPath)

	emittedNames := make(map[string]bool)
	var results []GeneratedFile

	for _, kind := range partitionOrder {
		if !partitionByTier && kind != PartitionDefault {
			continue
		}
		if tier2Only && !isSiblingPartition(kind) {
			continue
		}
		if pkgTier == PackageTierShared && kind == PartitionLinux {
			continue
		}
		if pkgTier == PackageTier1 && kind == PartitionUnsafe {
			continue
		}

		typesInPart := partTypes[kind]
		filesInPart := partFiles[kind]
		canonicalName := OutputFileName(pkgName, kind)

		if len(typesInPart) == 0 {
			shouldEmitEmpty := false
			switch kind {
			case PartitionDefault:
				shouldEmitEmpty = len(filesInPart) > 0 || !partitionByTier
			case PartitionUnsafe:
				shouldEmitEmpty = len(filesInPart) > 0
			}
			if !shouldEmitEmpty {
				continue
			}
			fileConstraints := make([]constraint.Expr, 0, len(filesInPart))
			for _, pf := range filesInPart {
				fileConstraints = append(fileConstraints, pf.constraint)
			}
			headerConstraint := CombineEmptyPartitionConstraints(fileConstraints)
			formatted, emitErr := emitPartitionFile(
				pkgName,
				normPkg,
				stateImportPath,
				headerConstraint,
				nil,
				nil,
				nil,
				nil,
				nil,
				nil,
			)
			if emitErr != nil {
				return nil, fmt.Errorf("emit %s: %w", canonicalName, emitErr)
			}
			emittedNames[canonicalName] = true
			results = append(results, GeneratedFile{
				Partition: kind,
				BaseName:  canonicalName,
				Present:   true,
				Content:   formatted,
			})
			continue
		}

		groups := buildConstraintSubGroups(pkgName, kind, typesInPart)

		// If PartitionDefault or PartitionUnsafe has unconstrained non-savable files alongside
		// arch-constrained savable files, keep the canonical empty autogen file as well.
		if (kind == PartitionDefault || kind == PartitionUnsafe) && !containsFileName(groups, canonicalName) {
			hasCanonicalSource := false
			for _, pf := range filesInPart {
				if EquivalentConstraints(pf.constraint, CanonicalPartitionConstraint(kind)) {
					hasCanonicalSource = true
					break
				}
			}
			if hasCanonicalSource {
				formatted, emitErr := emitPartitionFile(
					pkgName,
					normPkg,
					stateImportPath,
					CanonicalPartitionConstraint(kind),
					nil,
					nil,
					nil,
					nil,
					nil,
					nil,
				)
				if emitErr != nil {
					return nil, fmt.Errorf("emit %s: %w", canonicalName, emitErr)
				}
				emittedNames[canonicalName] = true
				results = append(results, GeneratedFile{
					Partition: kind,
					BaseName:  canonicalName,
					Present:   true,
					Content:   formatted,
				})
			}
		}

		for _, grp := range groups {
			env, envErr := buildScopedEnv(pkgTier, kind, grp.constraint, grp.types, files)
			if envErr != nil {
				return nil, envErr
			}
			formatted, emitErr := emitPartitionFile(
				pkgName,
				normPkg,
				stateImportPath,
				grp.constraint,
				grp.types,
				env.localTypes,
				env.receivers,
				env.beforeSaveHooks,
				env.afterLoadHooks,
				env.pkgImports,
			)
			if emitErr != nil {
				return nil, fmt.Errorf("emit %s: %w", grp.outName, emitErr)
			}
			emittedNames[grp.outName] = true
			results = append(results, GeneratedFile{
				Partition: kind,
				BaseName:  grp.outName,
				Present:   true,
				Content:   formatted,
			})
		}
	}

	// Mark stale owned autogen files on disk for removal or -check failure.
	for _, diskName := range rawAutogenNames {
		if emittedNames[diskName] {
			continue
		}
		diskPart, owned := classifyExistingAutogen(pkgTier, pkgName, diskName, partitionByTier, tier2Only)
		if !owned {
			continue
		}
		results = append(results, GeneratedFile{
			Partition: diskPart,
			BaseName:  diskName,
			Present:   false,
		})
	}

	return results, nil
}

func buildConstraintSubGroups(pkgName string, kind PartitionKind, savables []*savableTypeGen) []subPartitionGroup {
	var groups []subPartitionGroup
	for _, st := range savables {
		idx := -1
		for i := range groups {
			if EquivalentConstraints(groups[i].constraint, st.file.constraint) {
				idx = i
				break
			}
		}
		if idx < 0 {
			groups = append(groups, subPartitionGroup{
				constraint: st.file.constraint,
				types:      []*savableTypeGen{st},
			})
		} else {
			groups[idx].types = append(groups[idx].types, st)
		}
	}

	usedNames := make(map[string]int, len(groups))
	for i := range groups {
		cand := SubPartitionOutputFileName(pkgName, kind, groups[i].constraint)
		if count := usedNames[cand]; count > 0 {
			stem := strings.TrimSuffix(cand, "_state_autogen.go")
			cand = fmt.Sprintf("%s_%d_state_autogen.go", stem, count+1)
		}
		usedNames[cand]++
		groups[i].outName = cand
	}

	canonical := OutputFileName(pkgName, kind)
	slices.SortFunc(groups, func(a, b subPartitionGroup) int {
		aCanon := a.outName == canonical
		bCanon := b.outName == canonical
		if aCanon != bCanon {
			if aCanon {
				return -1
			}
			return 1
		}
		return cmp.Compare(a.outName, b.outName)
	})
	return groups
}

func containsFileName(groups []subPartitionGroup, target string) bool {
	for _, g := range groups {
		if g.outName == target {
			return true
		}
	}
	return false
}

func classifyExistingAutogen(pkgTier PackageTier, pkgName, baseName string, partitionByTier, tier2Only bool) (PartitionKind, bool) {
	if !partitionByTier {
		if baseName == OutputFileName(pkgName, PartitionDefault) {
			return PartitionDefault, true
		}
		return "", false
	}
	switch {
	case hasUnderscoreToken(baseName, "darwin"):
		return PartitionDarwin, true
	case hasUnderscoreToken(baseName, "windows"):
		return PartitionWindows, true
	case hasUnderscoreToken(baseName, "xplat"):
		return PartitionXplat, true
	case pkgTier == PackageTier1 && hasUnderscoreToken(baseName, "linux"):
		return PartitionLinux, true
	case tier2Only:
		return "", false
	case pkgTier == PackageTier1:
		return PartitionDefault, true
	default:
		// In shared packages, leave auxiliary Tier 3 upstream Bazel autogen files untouched.
		return "", false
	}
}

type scopedEnv struct {
	localTypes      map[string]localTypeDef
	receivers       map[string]string
	beforeSaveHooks map[string]bool
	afterLoadHooks  map[string]bool
	pkgImports      map[string]importRef
}

func buildScopedEnv(
	pkgTier PackageTier,
	targetPart PartitionKind,
	targetConstraint constraint.Expr,
	groupTypes []*savableTypeGen,
	allFiles []*parsedSourceFile,
) (*scopedEnv, error) {
	env := &scopedEnv{
		localTypes:      make(map[string]localTypeDef),
		receivers:       make(map[string]string),
		beforeSaveHooks: make(map[string]bool),
		afterLoadHooks:  make(map[string]bool),
		pkgImports:      make(map[string]importRef),
	}

	structByName := make(map[string]*savableTypeGen, len(groupTypes))
	for _, st := range groupTypes {
		if st.kind == typeKindStruct {
			structByName[st.name] = st
		}
	}

	for _, sf := range allFiles {
		canSupply := partitionCanSupply(pkgTier, sf.partition, targetPart) && CoversConstraint(sf.constraint, targetConstraint)

		for _, m := range sf.methods {
			if m.funcName != "beforeSave" && m.funcName != "afterLoad" {
				continue
			}
			st, isTargetStruct := structByName[m.recvType]
			if !isTargetStruct {
				continue
			}
			if AreMutuallyExclusive(sf.constraint, st.file.constraint) {
				continue
			}
			if pkgTier == PackageTierShared && isTier3Partition(targetPart) && !isTier3Partition(sf.partition) {
				return nil, fmt.Errorf(
					"%s: cross-tier %s hook on Tier 3 struct %s (declared in %s) is forbidden",
					sf.baseName, m.funcName, st.name, st.file.baseName,
				)
			}
			if !partitionCanSupply(pkgTier, sf.partition, targetPart) || !CoversConstraint(sf.constraint, st.file.constraint) {
				return nil, fmt.Errorf(
					"%s: %s hook with constraint %q does not cover struct %s in %s (constraint %q)",
					sf.baseName, m.funcName, formatConstraintLabel(sf.constraint),
					st.name, st.file.baseName, formatConstraintLabel(st.file.constraint),
				)
			}
		}

		if !canSupply {
			continue
		}
		for k, v := range sf.imports {
			if _, exists := env.pkgImports[k]; !exists {
				env.pkgImports[k] = v
			}
		}
		for _, lt := range sf.localTypes {
			env.localTypes[lt.name] = lt.def
		}
		for _, m := range sf.methods {
			if m.recvVar != "" {
				env.receivers[m.recvType] = m.recvVar
			}
			switch m.funcName {
			case "beforeSave":
				env.beforeSaveHooks[m.recvType] = true
			case "afterLoad":
				env.afterLoadHooks[m.recvType] = true
			}
		}
	}

	return env, nil
}

func formatConstraintLabel(expr constraint.Expr) string {
	if expr == nil {
		return "unconstrained"
	}
	return expr.String()
}

// findAuxiliaryTier3AutogenTypes inspects upstream sub-target autogen files (such as
// kernel_opts_state_autogen.go or arch_x86_impl_state_autogen.go) scoped by build constraint
// so regenerating <pkg>_state_autogen.go never redeclares overlapping auxiliary types while
// preserving sibling architecture types.
func findAuxiliaryTier3AutogenTypes(fset *token.FileSet, absDir, pkgName string, pkgTier PackageTier, autogenNames []string) (map[string][]constraint.Expr, error) {
	claimed := make(map[string][]constraint.Expr)
	if pkgTier != PackageTierShared {
		return claimed, nil
	}
	mainOut := OutputFileName(pkgName, PartitionDefault)
	unsafeOut := OutputFileName(pkgName, PartitionUnsafe)
	for _, name := range autogenNames {
		if name == mainOut || name == unsafeOut {
			continue
		}
		if hasUnderscoreToken(name, "xplat") || hasUnderscoreToken(name, "darwin") || hasUnderscoreToken(name, "windows") {
			continue
		}
		fullPath := filepath.Join(absDir, name)
		src, readErr := os.ReadFile(fullPath)
		if readErr != nil {
			return nil, fmt.Errorf("read auxiliary autogen %s: %w", fullPath, readErr)
		}
		auxConstraint, cErr := ExtractFileConstraint(name, src)
		if cErr != nil {
			return nil, cErr
		}
		af, err := parser.ParseFile(fset, fullPath, src, 0)
		if err != nil {
			return nil, fmt.Errorf("parse auxiliary autogen %s: %w", fullPath, err)
		}
		for _, decl := range af.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok || fd.Name.Name != "StateTypeName" || fd.Recv == nil || len(fd.Recv.List) == 0 {
				continue
			}
			if recvType := baseReceiverTypeName(fd.Recv.List[0].Type); recvType != "" {
				claimed[recvType] = append(claimed[recvType], auxConstraint)
			}
		}
	}
	return claimed, nil
}

func isClaimedByAuxiliary(typeName string, fileConstraint constraint.Expr, claimed map[string][]constraint.Expr) bool {
	auxList, exists := claimed[typeName]
	if !exists {
		return false
	}
	for _, auxConstraint := range auxList {
		if !AreMutuallyExclusive(auxConstraint, fileConstraint) {
			return true
		}
	}
	return false
}

func collectFileImports(f *ast.File) map[string]importRef {
	out := make(map[string]importRef, len(f.Imports))
	for _, imp := range f.Imports {
		impPath, err := strconv.Unquote(imp.Path.Value)
		if err != nil || impPath == "" {
			continue
		}
		var localName string
		var alias string
		if imp.Name != nil {
			if imp.Name.Name == "_" || imp.Name.Name == "." {
				continue
			}
			localName = imp.Name.Name
			if localName != path.Base(impPath) {
				alias = localName
			}
		} else {
			localName = path.Base(impPath)
		}
		out[localName] = importRef{alias: alias, path: impPath}
	}
	return out
}

func baseReceiverTypeName(expr ast.Expr) string {
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.IndexExpr:
		if id, ok := e.X.(*ast.Ident); ok {
			return id.Name
		}
	case *ast.IndexListExpr:
		if id, ok := e.X.(*ast.Ident); ok {
			return id.Name
		}
	}
	return ""
}

func extractSavableTypes(fset *token.FileSet, pf *parsedSourceFile, skipTypes map[string][]constraint.Expr) ([]*savableTypeGen, error) {
	var out []*savableTypeGen
	for _, decl := range pf.astFile.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		declSavable, declIdent, err := parseStateifyComments(gd.Doc)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", pf.baseName, err)
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			specSavable, specIdent, sErr := parseStateifyComments(ts.Doc)
			if sErr != nil {
				return nil, fmt.Errorf("%s (%s): %w", pf.baseName, ts.Name.Name, sErr)
			}
			isSavable := declSavable || specSavable
			isIdent := declIdent || specIdent
			if !isSavable {
				continue
			}
			if isClaimedByAuxiliary(ts.Name.Name, pf.constraint, skipTypes) {
				continue
			}
			if ts.Assign.IsValid() {
				continue
			}
			if _, isIface := ts.Type.(*ast.InterfaceType); isIface {
				continue
			}
			if ts.TypeParams != nil && len(ts.TypeParams.List) > 0 {
				return nil, fmt.Errorf("%s: generic type %s cannot use +stateify savable", pf.baseName, ts.Name.Name)
			}

			if isIdent {
				var buf bytes.Buffer
				if pErr := printer.Fprint(&buf, fset, ts.Type); pErr != nil {
					return nil, fmt.Errorf("%s (%s): %w", pf.baseName, ts.Name.Name, pErr)
				}
				out = append(out, &savableTypeGen{
					name:         ts.Name.Name,
					kind:         typeKindIdent,
					file:         pf,
					identBase:    buf.String(),
					identBaseAST: ts.Type,
				})
				continue
			}

			st, isStruct := ts.Type.(*ast.StructType)
			if !isStruct {
				out = append(out, &savableTypeGen{
					name: ts.Name.Name,
					kind: typeKindValue,
					file: pf,
				})
				continue
			}

			rawFields, fErr := extractStructFields(pf, ts.Name.Name, st)
			if fErr != nil {
				return nil, fErr
			}
			out = append(out, &savableTypeGen{
				name:      ts.Name.Name,
				kind:      typeKindStruct,
				file:      pf,
				rawFields: rawFields,
			})
		}
	}
	return out, nil
}

func parseStateifyComments(cg *ast.CommentGroup) (savable, identType bool, err error) {
	if cg == nil {
		return false, false, nil
	}
	for _, c := range cg.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		rest, ok := strings.CutPrefix(text, "+stateify")
		if !ok {
			continue
		}
		for tok := range strings.FieldsSeq(rest) {
			switch tok {
			case "savable":
				savable = true
			case "identtype":
				identType = true
			default:
				return false, false, fmt.Errorf("unsupported +stateify directive %q", tok)
			}
		}
	}
	return savable, identType, nil
}

func extractStructFields(pf *parsedSourceFile, structName string, st *ast.StructType) ([]rawFieldSpec, error) {
	if st.Fields == nil {
		return nil, nil
	}
	var fields []rawFieldSpec
	for _, f := range st.Fields.List {
		stateTag, err := parseStructStateTag(f.Tag)
		if err != nil {
			return nil, fmt.Errorf("%s (%s): %w", pf.baseName, structName, err)
		}
		if stateTag == "nosave" {
			continue
		}

		kind := fieldNormal
		var valTypeStr string
		var parsedValExpr ast.Expr
		switch {
		case stateTag == "":
			kind = fieldNormal
		case stateTag == "wait":
			kind = fieldWait
		case stateTag == "zerovalue":
			kind = fieldZeroValue
		case strings.HasPrefix(stateTag, ".(") && strings.HasSuffix(stateTag, ")"):
			rawType := strings.TrimSpace(stateTag[2 : len(stateTag)-1])
			parsedExpr, pErr := parser.ParseExpr(rawType)
			if pErr != nil {
				return nil, fmt.Errorf("%s (%s): invalid state value type %q: %w", pf.baseName, structName, stateTag, pErr)
			}
			var buf bytes.Buffer
			if fErr := printer.Fprint(&buf, token.NewFileSet(), parsedExpr); fErr != nil {
				return nil, fmt.Errorf("%s (%s): %w", pf.baseName, structName, fErr)
			}
			kind = fieldValue
			valTypeStr = buf.String()
			parsedValExpr = parsedExpr
		default:
			return nil, fmt.Errorf("%s (%s): unsupported state struct tag %q", pf.baseName, structName, stateTag)
		}

		var names []string
		if len(f.Names) == 0 {
			embName := embeddedFieldName(f.Type)
			if embName != "" && embName != "_" {
				names = []string{embName}
			}
		} else {
			for _, id := range f.Names {
				if id.Name != "_" {
					names = append(names, id.Name)
				}
			}
		}

		for _, name := range names {
			fields = append(fields, rawFieldSpec{
				name:          name,
				kind:          kind,
				typeExpr:      f.Type,
				valueType:     valTypeStr,
				parsedValExpr: parsedValExpr,
			})
		}
	}
	return fields, nil
}

func parseStructStateTag(tagLit *ast.BasicLit) (string, error) {
	if tagLit == nil {
		return "", nil
	}
	unquoted, err := strconv.Unquote(tagLit.Value)
	if err != nil {
		return "", fmt.Errorf("unquote struct tag %s: %w", tagLit.Value, err)
	}
	return reflect.StructTag(unquoted).Get("state"), nil
}

func embeddedFieldName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		return e.Sel.Name
	case *ast.StarExpr:
		return embeddedFieldName(e.X)
	case *ast.IndexExpr:
		return embeddedFieldName(e.X)
	case *ast.IndexListExpr:
		return embeddedFieldName(e.X)
	default:
		return ""
	}
}

func collectExprImports(expr ast.Expr, fileImports, scopedPkgImports map[string]importRef) []importRef {
	if expr == nil {
		return nil
	}
	var imps []importRef
	seen := make(map[string]bool)
	ast.Inspect(expr, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		pkgIdent, ok := sel.X.(*ast.Ident)
		if !ok {
			return true
		}
		ref, found := fileImports[pkgIdent.Name]
		if !found {
			ref, found = scopedPkgImports[pkgIdent.Name]
		}
		if found && !seen[ref.path] {
			seen[ref.path] = true
			imps = append(imps, ref)
		}
		return false
	})
	return imps
}

func normalizeTypePkgPath(pkgPath, modPath string) string {
	if modPath != "" {
		if rest, ok := strings.CutPrefix(pkgPath, modPath+"/"); ok {
			return rest
		}
	}
	for _, prefix := range []string{defaultModulePath + "/", upstreamModulePath + "/"} {
		if rest, ok := strings.CutPrefix(pkgPath, prefix); ok {
			return rest
		}
	}
	return pkgPath
}

func resolveStateImportPath(modPath string) string {
	if modPath == upstreamModulePath {
		return upstreamModulePath + "/pkg/state"
	}
	return defaultModulePath + "/pkg/state"
}

type primitiveResolution struct {
	ok        bool
	suffix    string
	castType  string
	needsCast bool
}

func resolveLocalPrimitive(expr ast.Expr, localTypes map[string]localTypeDef) primitiveResolution {
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return primitiveResolution{}
	}
	name := ident.Name
	definedSteps := 0
	visited := make(map[string]bool)
	for {
		if visited[name] {
			return primitiveResolution{}
		}
		visited[name] = true

		def, exists := localTypes[name]
		if !exists {
			if info, isPrim := primitiveTypedNames[name]; isPrim {
				return primitiveResolution{
					ok:        true,
					suffix:    info.suffix,
					castType:  info.castType,
					needsCast: definedSteps > 0,
				}
			}
			return primitiveResolution{}
		}
		if !def.isAlias {
			definedSteps++
		}
		nextIdent, ok := def.rhs.(*ast.Ident)
		if !ok {
			return primitiveResolution{}
		}
		name = nextIdent.Name
	}
}

func receiverFor(typeName string, receivers map[string]string) string {
	if r, ok := receivers[typeName]; ok && r != "" {
		return r
	}
	first, _ := utf8.DecodeRuneInString(typeName)
	cand := string(unicode.ToLower(first))
	if reservedReceiverNames[cand] {
		return "x"
	}
	return cand
}

func upperFirst(s string) string {
	if s == "" {
		return ""
	}
	r, size := utf8.DecodeRuneInString(s)
	return string(unicode.ToUpper(r)) + s[size:]
}

func emitPartitionFile(
	pkgName string,
	normPkg string,
	stateImportPath string,
	headerConstraint constraint.Expr,
	savables []*savableTypeGen,
	localTypes map[string]localTypeDef,
	receivers map[string]string,
	beforeSaveHooks map[string]bool,
	afterLoadHooks map[string]bool,
	scopedPkgImports map[string]importRef,
) ([]byte, error) {
	var hdr bytes.Buffer
	hdr.WriteString(autogenHeader)
	if headerConstraint != nil {
		fmt.Fprintf(&hdr, "//go:build %s\n\n", headerConstraint.String())
	}
	fmt.Fprintf(&hdr, "package %s\n", pkgName)

	if len(savables) == 0 {
		return format.Source(hdr.Bytes())
	}

	needsContext := false
	extraImports := make(map[string]importRef)
	var body bytes.Buffer
	var initLines []string

	for _, st := range savables {
		recv := receiverFor(st.name, receivers)
		fullTypeName := normPkg + "." + st.name
		if normPkg == "" {
			fullTypeName = st.name
		}

		switch st.kind {
		case typeKindValue:
			fmt.Fprintf(&body, "\nfunc (%s *%s) StateTypeName() string {\n\treturn %q\n}\n", recv, st.name, fullTypeName)
			fmt.Fprintf(&body, "\nfunc (%s *%s) StateFields() []string {\n\treturn nil\n}\n", recv, st.name)
			initLines = append(initLines, fmt.Sprintf("\tstate.Register((*%s)(nil))", st.name))

		case typeKindIdent:
			needsContext = true
			for _, imp := range collectExprImports(st.identBaseAST, st.file.imports, scopedPkgImports) {
				extraImports[imp.path] = imp
			}
			fmt.Fprintf(&body, "\nfunc (%s *%s) StateTypeName() string {\n\treturn %q\n}\n", recv, st.name, fullTypeName)
			fmt.Fprintf(&body, "\nfunc (%s *%s) StateFields() []string {\n\treturn (*%s)(%s).StateFields()\n}\n", recv, st.name, st.identBase, recv)
			fmt.Fprintf(&body, "\n// +checklocksignore\nfunc (%s *%s) StateSave(stateSinkObject state.Sink) {\n\t(*%s)(%s).StateSave(stateSinkObject)\n}\n", recv, st.name, st.identBase, recv)
			fmt.Fprintf(&body, "\n// +checklocksignore\nfunc (%s *%s) StateLoad(ctx context.Context, stateSourceObject state.Source) {\n\t(*%s)(%s).StateLoad(ctx, stateSourceObject)\n}\n", recv, st.name, st.identBase, recv)
			initLines = append(initLines, fmt.Sprintf("\tstate.RegisterIdent((*%s)(nil), (*%s)(nil))", st.name, st.identBase))

		case typeKindStruct:
			needsContext = true
			hasBeforeSave := beforeSaveHooks[st.name]
			hasAfterLoad := afterLoadHooks[st.name]

			type slottedField struct {
				slot  int
				field structFieldGen
			}
			var slotted []slottedField
			var zeroFields []structFieldGen
			var valueFields []slottedField

			for _, rf := range st.rawFields {
				fg := structFieldGen{
					name:      rf.name,
					kind:      rf.kind,
					typeExpr:  rf.typeExpr,
					valueType: rf.valueType,
					extraImps: collectExprImports(rf.parsedValExpr, st.file.imports, scopedPkgImports),
				}
				for _, imp := range fg.extraImps {
					extraImports[imp.path] = imp
				}
				if fg.kind == fieldZeroValue {
					zeroFields = append(zeroFields, fg)
					continue
				}
				slot := len(slotted)
				sf := slottedField{slot: slot, field: fg}
				slotted = append(slotted, sf)
				if fg.kind == fieldValue {
					valueFields = append(valueFields, sf)
				}
			}

			fmt.Fprintf(&body, "\nfunc (%s *%s) StateTypeName() string {\n\treturn %q\n}\n", recv, st.name, fullTypeName)
			if len(slotted) == 0 {
				fmt.Fprintf(&body, "\nfunc (%s *%s) StateFields() []string {\n\treturn []string{}\n}\n", recv, st.name)
			} else {
				fmt.Fprintf(&body, "\nfunc (%s *%s) StateFields() []string {\n\treturn []string{\n", recv, st.name)
				for _, sf := range slotted {
					fmt.Fprintf(&body, "\t\t%q,\n", sf.field.name)
				}
				body.WriteString("\t}\n}\n")
			}

			if !hasBeforeSave {
				fmt.Fprintf(&body, "\nfunc (%s *%s) beforeSave() {}\n", recv, st.name)
			}

			fmt.Fprintf(&body, "\n// +checklocksignore\nfunc (%s *%s) StateSave(stateSinkObject state.Sink) {\n", recv, st.name)
			fmt.Fprintf(&body, "\t%s.beforeSave()\n", recv)
			for _, zf := range zeroFields {
				fmt.Fprintf(&body, "\tif !state.IsZeroValue(&%s.%s) {\n\t\tstate.Failf(\"%s is %%#v, expected zero\", &%s.%s)\n\t}\n",
					recv, zf.name, zf.name, recv, zf.name)
			}
			for _, vf := range valueFields {
				valVar := vf.field.name + "Value"
				fmt.Fprintf(&body, "\t%s := %s.save%s()\n", valVar, recv, upperFirst(vf.field.name))
				fmt.Fprintf(&body, "\t_ = (%s)(%s)\n", vf.field.valueType, valVar)
			}
			for _, sf := range slotted {
				if sf.field.kind == fieldValue {
					continue
				}
				if sf.field.kind == fieldWait {
					fmt.Fprintf(&body, "\tstateSinkObject.Save(%d, &%s.%s)\n", sf.slot, recv, sf.field.name)
					continue
				}
				prim := resolveLocalPrimitive(sf.field.typeExpr, localTypes)
				if prim.ok {
					if prim.needsCast {
						fmt.Fprintf(&body, "\tstateSinkObject.Save%s(%d, (*%s)(&%s.%s))\n", prim.suffix, sf.slot, prim.castType, recv, sf.field.name)
					} else {
						fmt.Fprintf(&body, "\tstateSinkObject.Save%s(%d, &%s.%s)\n", prim.suffix, sf.slot, recv, sf.field.name)
					}
				} else {
					fmt.Fprintf(&body, "\tstateSinkObject.Save(%d, &%s.%s)\n", sf.slot, recv, sf.field.name)
				}
			}
			for _, vf := range valueFields {
				fmt.Fprintf(&body, "\tstateSinkObject.SaveValue(%d, %sValue)\n", vf.slot, vf.field.name)
			}
			body.WriteString("}\n")

			if !hasAfterLoad {
				fmt.Fprintf(&body, "\nfunc (%s *%s) afterLoad(context.Context) {}\n", recv, st.name)
			}

			fmt.Fprintf(&body, "\n// +checklocksignore\nfunc (%s *%s) StateLoad(ctx context.Context, stateSourceObject state.Source) {\n", recv, st.name)
			for _, sf := range slotted {
				if sf.field.kind == fieldValue {
					continue
				}
				if sf.field.kind == fieldWait {
					fmt.Fprintf(&body, "\tstateSourceObject.LoadWait(%d, &%s.%s)\n", sf.slot, recv, sf.field.name)
					continue
				}
				prim := resolveLocalPrimitive(sf.field.typeExpr, localTypes)
				if prim.ok {
					if prim.needsCast {
						fmt.Fprintf(&body, "\tstateSourceObject.Load%s(%d, (*%s)(&%s.%s))\n", prim.suffix, sf.slot, prim.castType, recv, sf.field.name)
					} else {
						fmt.Fprintf(&body, "\tstateSourceObject.Load%s(%d, &%s.%s)\n", prim.suffix, sf.slot, recv, sf.field.name)
					}
				} else {
					fmt.Fprintf(&body, "\tstateSourceObject.Load(%d, &%s.%s)\n", sf.slot, recv, sf.field.name)
				}
			}
			for _, vf := range valueFields {
				fmt.Fprintf(&body, "\tstateSourceObject.LoadValueTo(%d, (*%s)(nil), %s)\n", vf.slot, vf.field.valueType, recv)
			}
			if hasAfterLoad {
				fmt.Fprintf(&body, "\tstateSourceObject.AfterLoadTo(%s)\n", recv)
			}
			body.WriteString("}\n")

			if len(valueFields) > 0 {
				fmt.Fprintf(&body, "\n// +checklocksignore\nfunc (%s *%s) StateLoadValue(ctx context.Context, stateSlot int, stateValue any) {\n\tswitch stateSlot {\n", recv, st.name)
				for _, vf := range valueFields {
					fmt.Fprintf(&body, "\tcase %d:\n\t\t%s.load%s(ctx, stateValue.(%s))\n",
						vf.slot, recv, upperFirst(vf.field.name), vf.field.valueType)
				}
				body.WriteString("\t}\n}\n")
			}

			if hasAfterLoad {
				fmt.Fprintf(&body, "\n// +checklocksignore\nfunc (%s *%s) StateAfterLoad(ctx context.Context) {\n\t%s.afterLoad(ctx)\n}\n", recv, st.name, recv)
			}

			if hasBeforeSave || hasAfterLoad {
				initLines = append(initLines, fmt.Sprintf("\tstate.RegisterStruct((*%s)(nil))", st.name))
			} else {
				initLines = append(initLines, fmt.Sprintf("\tstate.RegisterNoHooks((*%s)(nil))", st.name))
			}
		}
	}

	extraImports[stateImportPath] = importRef{path: stateImportPath}
	var stdImps []importRef
	var extImps []importRef
	if needsContext {
		stdImps = append(stdImps, importRef{path: "context"})
	}
	for _, imp := range extraImports {
		if imp.path == "context" {
			continue
		}
		if isStdlibImport(imp.path) {
			stdImps = append(stdImps, imp)
		} else {
			extImps = append(extImps, imp)
		}
	}
	slices.SortFunc(stdImps, compareImportRef)
	slices.SortFunc(extImps, compareImportRef)

	hdr.WriteString("\nimport (\n")
	for _, imp := range stdImps {
		writeImportLine(&hdr, imp)
	}
	if len(stdImps) > 0 && len(extImps) > 0 {
		hdr.WriteByte('\n')
	}
	for _, imp := range extImps {
		writeImportLine(&hdr, imp)
	}
	hdr.WriteString(")\n")

	hdr.Write(body.Bytes())
	hdr.WriteString("\nfunc init() {\n")
	for _, line := range initLines {
		hdr.WriteString(line)
		hdr.WriteByte('\n')
	}
	hdr.WriteString("}\n")

	formatted, err := format.Source(hdr.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated code: %w\n%s", err, hdr.String())
	}
	return formatted, nil
}

func isStdlibImport(impPath string) bool {
	first, _, _ := strings.Cut(impPath, "/")
	return !strings.Contains(first, ".")
}

func compareImportRef(a, b importRef) int {
	return cmp.Compare(a.path, b.path)
}

func writeImportLine(buf *bytes.Buffer, imp importRef) {
	if imp.alias != "" {
		fmt.Fprintf(buf, "\t%s %q\n", imp.alias, imp.path)
		return
	}
	fmt.Fprintf(buf, "\t%q\n", imp.path)
}

func unifiedLineDiff(relPath, wantDisk, gotGen string) string {
	diskLines := splitLinesKeepEmpty(wantDisk)
	genLines := splitLinesKeepEmpty(gotGen)

	var sb strings.Builder
	fmt.Fprintf(&sb, "--- on-disk/%s\n+++ generated/%s\n", relPath, relPath)
	maxLen := max(len(diskLines), len(genLines))
	diffCount := 0
	for i := range maxLen {
		var dLine, gLine string
		hasD := i < len(diskLines)
		hasG := i < len(genLines)
		if hasD {
			dLine = diskLines[i]
		}
		if hasG {
			gLine = genLines[i]
		}
		if hasD && hasG && dLine == gLine {
			continue
		}
		fmt.Fprintf(&sb, "@@ line %d @@\n", i+1)
		if hasD {
			fmt.Fprintf(&sb, "-%s\n", dLine)
		}
		if hasG {
			fmt.Fprintf(&sb, "+%s\n", gLine)
		}
		diffCount++
		if diffCount >= 25 {
			sb.WriteString("... (diff truncated)\n")
			break
		}
	}
	return sb.String()
}

func splitLinesKeepEmpty(s string) []string {
	if s == "" {
		return nil
	}
	s = strings.TrimSuffix(s, "\n")
	return strings.Split(s, "\n")
}
