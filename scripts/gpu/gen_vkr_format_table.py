"""Writes src/venus/vkr_format_table.h of the pinned virglrenderer patch
0003-vkr-check-image-and-view-create-info.patch from the Vulkan registry.

Usage:
  python3 -I scripts/gpu/gen_vkr_format_table.py \\
      build/gpu/cache/venus-protocol-<commit>/xmls/vk.xml >vkr_format_table.h

The registry gives the compatibility class, the texel block size, the chroma
subsampling, and the compatible plane formats of each format. Run the script
again and put the output in the patch when VENUS_PROTOCOL_COMMIT changes.
"""

import sys
import xml.etree.ElementTree as ET

FLAG_COMPRESSED = 1
FLAG_CHROMA_420 = 2
FLAG_CHROMA_422 = 4


def format_values(root):
    """Returns the value of each VkFormat name that is not an alias."""
    values = {}
    for enums in root.iter("enums"):
        if enums.get("name") != "VkFormat":
            continue
        for enum in enums.iter("enum"):
            if enum.get("value") is not None:
                values[enum.get("name")] = int(enum.get("value"), 0)
    for parent in list(root.iter("extension")) + list(root.iter("feature")):
        parent_number = parent.get("number")
        for enum in parent.iter("enum"):
            if enum.get("extends") != "VkFormat" or enum.get("alias") is not None:
                continue
            if enum.get("offset") is None:
                continue
            number = enum.get("extnumber") or parent_number
            values[enum.get("name")] = 1000000000 + (int(number) - 1) * 1000 + int(enum.get("offset"))
    return values


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: gen_vkr_format_table.py <vk.xml>\n")
        return 2
    root = ET.parse(sys.argv[1]).getroot()
    values = format_values(root)

    formats = []
    planes = []
    classes = {}
    for fmt in root.iter("format"):
        name = fmt.get("name")
        if name not in values:
            raise SystemExit("no value for " + name)
        class_id = classes.setdefault(fmt.get("class"), len(classes) + 1)
        flags = 0
        if fmt.get("compressed") is not None:
            flags |= FLAG_COMPRESSED
        chroma = fmt.get("chroma")
        if chroma == "420":
            flags |= FLAG_CHROMA_420
        elif chroma == "422":
            flags |= FLAG_CHROMA_422
        fmt_planes = sorted(fmt.findall("plane"), key=lambda p: int(p.get("index")))
        # The block size of a multi-planar format is the sum of its planes.
        block_size = 0 if fmt_planes else int(fmt.get("blockSize"))
        formats.append((values[name], name, class_id, block_size, flags, len(fmt_planes)))
        if fmt_planes:
            compatible = [values[p.get("compatible")] for p in fmt_planes]
            planes.append((values[name], name, compatible + [0] * (3 - len(compatible))))
    formats.sort()
    planes.sort()

    out = sys.stdout.write
    out("/*\n * Copyright 2026 The gVisor Authors\n * SPDX-License-Identifier: MIT\n */\n\n")
    out("/* This file is generated by scripts/gpu/gen_vkr_format_table.py of gvx from\n")
    out(" * xmls/vk.xml of venus-protocol.  Do not edit.\n */\n\n")
    out("#ifndef VKR_FORMAT_TABLE_H\n#define VKR_FORMAT_TABLE_H\n\n#include <stdint.h>\n\n")
    out("#define VKR_FORMAT_FLAG_COMPRESSED %du\n" % FLAG_COMPRESSED)
    out("#define VKR_FORMAT_FLAG_CHROMA_420 %du\n" % FLAG_CHROMA_420)
    out("#define VKR_FORMAT_FLAG_CHROMA_422 %du\n\n" % FLAG_CHROMA_422)
    out("struct vkr_format_entry {\n")
    out("   uint32_t format;\n")
    out("   uint16_t class_id;   /* formats of one compatibility class have one id */\n")
    out("   uint8_t block_size;  /* bytes of a texel block; 0 for a multi-planar format */\n")
    out("   uint8_t flags;\n")
    out("   uint8_t plane_count; /* 0 for a format that is not multi-planar */\n")
    out("};\n\n")
    out("/* sorted by format */\n")
    out("static const struct vkr_format_entry vkr_format_table[] = {\n")
    for value, name, class_id, block_size, flags, plane_count in formats:
        out("   { %du, %d, %d, %d, %d }, /* %s */\n" % (value, class_id, block_size, flags, plane_count, name[len("VK_FORMAT_"):]))
    out("};\n\n")
    out("struct vkr_format_planes {\n")
    out("   uint32_t format;\n")
    out("   uint32_t plane_formats[3]; /* the compatible format of each plane */\n")
    out("};\n\n")
    out("/* sorted by format */\n")
    out("static const struct vkr_format_planes vkr_format_planes_table[] = {\n")
    for value, name, compatible in planes:
        out("   { %du, { %du, %du, %du } }, /* %s */\n" % (value, compatible[0], compatible[1], compatible[2], name[len("VK_FORMAT_"):]))
    out("};\n\n#endif /* VKR_FORMAT_TABLE_H */\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
